const snapshot = (
  dailyRate: number,
  guaranteeAmount: number,
  startAt: string,
  endAt: string,
  exchangePlace: string,
): TermsSnapshot => ({
  dailyRate,
  guaranteeAmount,
  startAt,
  endAt,
  originalEndAt: endAt,
  exchangePlace,
  ...terms,
});

const slot = (
  id: string,
  startAt: string,
  endAt: string,
  status: 'AVAILABLE' | 'RESERVED' = 'AVAILABLE',
  reservationId?: string,
) => ({ id, startAt, endAt, status, reservationId });

const listing = (
  value: Omit<
    Listing,
    'media' | 'availabilitySlots' | 'availability' | 'terms'
  > &
    Partial<
      Pick<Listing, 'media' | 'availabilitySlots' | 'availability' | 'terms'>
    >,
): Listing => ({
  ...value,
  media: value.media ?? [
    {
      id: `media-${value.id}`,
      type: 'PHOTO',
      url: value.image,
      name: value.title,
    },
  ],
  availability: value.availability ?? [
    '27 sep',
    '28 sep',
    '30 sep',
    '1 oct',
    '2 oct',
  ],
  availabilitySlots: value.availabilitySlots ?? [
    slot(
      `slot-${value.id}`,
      '2026-09-26T00:00:00-05:00',
      '2026-12-31T23:59:00-05:00',
    ),
  ],
  terms: value.terms ?? terms,
});

const loan = (
  value: Omit<
    Loan,
    'currentReturnAt' | 'originalReturnAt' | 'extensions' | 'reschedules'
  > &
    Partial<
      Pick<
        Loan,
        'currentReturnAt' | 'originalReturnAt' | 'extensions' | 'reschedules'
      >
    >,
): Loan => ({
  ...value,
  currentReturnAt: value.currentReturnAt ?? value.snapshot.endAt,
  originalReturnAt: value.originalReturnAt ?? value.snapshot.originalEndAt,
  extensions: value.extensions ?? [],
  reschedules: value.reschedules ?? [],
});

